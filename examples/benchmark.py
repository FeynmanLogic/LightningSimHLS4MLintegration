def find_solution1(project_dir):
    """Find solution1 generated by Vitis HLS."""

    project_dir = Path(project_dir)

    matches = sorted(
        p for p in project_dir.rglob("solution1")
        if p.is_dir()
    )

    if not matches:
        raise RuntimeError(
            f"Could not find solution1 under {project_dir}"
        )

    if len(matches) > 1:
        raise RuntimeError(
            f"Multiple solution1 directories found under "
            f"{project_dir}"
        )

    return matches[0]


def find_report_files(solution):
    """Find Vitis HLS report files."""

    return list(Path(solution).rglob("*.rpt"))


def extract_latency_from_reports(solution):
    """
    Try to extract latency/cycle information from Vitis reports.

    The exact report format can vary with the Vitis version,
    so this function is deliberately conservative.
    """

    reports = find_report_files(solution)

    patterns = [
        r"Latency\s*[:=]\s*(\d+)",
        r"Total\s+Latency\s*[:=]\s*(\d+)",
        r"Latency.*?(\d+)\s*cycles",
    ]

    for report in reports:

        try:
            text = report.read_text(errors="ignore")
        except Exception:
            continue

        for pattern in patterns:

            match = re.search(
                pattern,
                text,
                re.IGNORECASE,
            )

            if match:
                try:
                    return int(match.group(1))
                except ValueError:
                    pass

    return None


def load_fifo_results():

    result_file = Path(
        "fifo_advisor_results.json"
    )

    if not result_file.exists():
        return None

    try:

        with open(result_file, "r") as f:
            return json.load(f)

    except Exception as exc:

        print(
            f"WARNING: Could not read FIFOAdvisor results: "
            f"{exc}"
        )

        return None


