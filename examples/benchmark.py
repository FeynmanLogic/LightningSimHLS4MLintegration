def main():

    print("=" * 80)
    print("hls4ml / LightningSim / FIFOAdvisor Benchmark")
    print("=" * 80)

    all_results = []

    for index, model_name in enumerate(
        MODELS,
        start=1,
    ):

        print(
            f"\n\n========== "
            f"MODEL {index}/{len(MODELS)} "
            f"=========="
        )

        try:

            result = benchmark_model(
                model_name
            )

            all_results.append(result)

        except Exception as exc:

            print(
                f"\nERROR while processing "
                f"{model_name}: {exc}"
            )

            all_results.append(
                {
                    "model": model_name,
                    "status": "FAILED",
                    "error": str(exc),
                }
            )

        # Save after every model.

        with open(
            RESULTS_FILE,
            "w",
        ) as f:

            json.dump(
                all_results,
                f,
                indent=4,
            )

    # ========================================================
    # Final summary
    # ========================================================

    print("\n\n")
    print("=" * 80)
    print("FINAL BENCHMARK RESULTS")
    print("=" * 80)

    for result in all_results:

        print(
            f"\n{result['model']}"
        )

        if result.get("status") == "FAILED":

            print(
                f"  FAILED: {result['error']}"
            )

            continue

        cosim_time = result[
            "cosimulation"
        ].get(
            "wall_time_seconds"
        )

        lightning_time = result[
            "lightningsim"
        ].get(
            "wall_time_seconds"
        )

        vitis_cycles = result[
            "cosimulation"
        ].get(
            "cycles"
        )

        speedup = result[
            "comparison"
        ].get(
            "speedup"
        )

        print(
            f"  Vitis Co-sim time : "
            f"{cosim_time:.3f} s"
        )

        print(
            f"  Vitis cycles      : "
            f"{vitis_cycles}"
        )

        print(
            f"  LightningSim time : "
            f"{lightning_time:.3f} s"
        )

        print(
            f"  LightningSim speedup : "
            f"{speedup:.2f}x"
            if speedup is not None
            else "  LightningSim speedup : N/A"
        )

    print("\n")
    print(
        f"Complete results written to "
        f"{RESULTS_FILE}"
    )


if __name__ == "__main__":
    main()
