#!/usr/bin/env python3

"""
Timing benchmark for hls4ml Vitis HLS co-simulation vs LightningSim.

For each model:

    1. Fetch the hls4ml example model
    2. Generate/build the Vitis HLS project
    3. Run Vitis C/RTL co-simulation and measure wall-clock time
    4. Run LightningSim directly through its Conda environment
    5. Measure LightningSim wall-clock time
    6. Calculate speedup
    7. Save results to JSON

This script does NOT use hls4ml.run_lightningsim().
It does NOT collect latency values.
"""

import json
import subprocess
import time
from pathlib import Path

import hls4ml


# ============================================================
# Configuration
# ============================================================

MODELS = [
    "KERAS_1layer.json",
    "KERAS_3layer.json",
    "KERAS_3layer_batch_norm.json",
]

RESULTS_FILE = Path("timing_benchmark_results.json")

LIGHTNINGSIM_ENV = "lightningsim"


# ============================================================
# JSON
# ============================================================

def save_results(results):
    with open(RESULTS_FILE, "w") as f:
        json.dump(results, f, indent=4)


# ============================================================
# Find solution1
# ============================================================

def find_solution1(model_name):
    """
    Find the solution1 directory generated by the current
    hls4ml build.

    We search below the current directory and use the most
    recently modified solution1 directory.
    """

    matches = [
        p
        for p in Path.cwd().rglob("solution1")
        if p.is_dir()
    ]

    if not matches:
        raise FileNotFoundError(
            f"No solution1 directory found for {model_name}"
        )

    matches.sort(
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )

    return matches[0].resolve()


# ============================================================
# Run Vitis co-simulation
# ============================================================

def run_vitis_cosimulation(hls_model, model_name):

    print("\n" + "=" * 80)
    print(f"VITIS CO-SIMULATION: {model_name}")
    print("=" * 80)

    print("\nStarting Vitis C/RTL co-simulation...")

    start = time.perf_counter()

    try:
        hls_model.build(
            csim=True,
            cosim=True,
        )

    except Exception as exc:

        elapsed = time.perf_counter() - start

        print("\n✗ Vitis co-simulation failed.")
        print(f"Time before failure: {elapsed:.3f} s")
        print(f"Error: {exc}")

        return {
            "status": "FAILED",
            "runtime_seconds": elapsed,
            "error": str(exc),
        }

    elapsed = time.perf_counter() - start

    print(
        f"\n✓ Vitis co-simulation completed."
    )

    print(
        f"Vitis co-simulation time: "
        f"{elapsed:.3f} seconds"
    )

    return {
        "status": "PASSED",
        "runtime_seconds": elapsed,
    }


# ============================================================
# Run LightningSim directly
# ============================================================

def run_lightningsim(solution, model_name):

    print("\n" + "=" * 80)
    print(f"LIGHTNINGSIM: {model_name}")
    print("=" * 80)

    print(
        f"\nSolution:\n{solution}"
    )

    cmd = [
        "conda",
        "run",
        "-n",
        LIGHTNINGSIM_ENV,
        "lightningsim",
        "--skip-wait-for-synthesis",
        "--cli",
        str(solution),
    ]

    print("\nRunning:")
    print(" ".join(cmd))
    print()

    start = time.perf_counter()

    try:

        result = subprocess.run(
            cmd,
            check=True,
        )

    except subprocess.CalledProcessError as exc:

        elapsed = time.perf_counter() - start

        print(
            "\n✗ LightningSim failed."
        )

        print(
            f"Time before failure: "
            f"{elapsed:.3f} seconds"
        )

        return {
            "status": "FAILED",
            "runtime_seconds": elapsed,
            "error": str(exc),
        }

    elapsed = time.perf_counter() - start

    print(
        "\n✓ LightningSim completed."
    )

    print(
        f"LightningSim time: "
        f"{elapsed:.3f} seconds"
    )

    return {
        "status": "PASSED",
        "runtime_seconds": elapsed,
    }


# ============================================================
# Benchmark one model
# ============================================================

def benchmark_model(model_name):

    print("\n\n" + "#" * 80)
    print(f"# {model_name}")
    print("#" * 80)

    # --------------------------------------------------------
    # Fetch model
    # --------------------------------------------------------

    print("\nFetching hls4ml example model...")

    config = hls4ml.utils.fetch_example_model(
        model_name,
        backend="Vitis",
    )

    # --------------------------------------------------------
    # Convert
    # --------------------------------------------------------

    print("Converting model...")

    hls_model = hls4ml.converters.keras_v2_to_hls(
        config
    )

    # --------------------------------------------------------
    # Vitis co-simulation
    # --------------------------------------------------------

    vitis = run_vitis_cosimulation(
        hls_model,
        model_name,
    )

    if vitis["status"] != "PASSED":

        return {
            "model": model_name,
            "status": "FAILED",
            "vitis_cosimulation": vitis,
        }

    # --------------------------------------------------------
    # Locate generated solution
    # --------------------------------------------------------

    print("\nLocating generated Vitis solution...")

    try:

        solution = find_solution1(
            model_name
        )

    except Exception as exc:

        return {
            "model": model_name,
            "status": "FAILED",
            "vitis_cosimulation": vitis,
            "error": str(exc),
        }

    print(
        f"✓ Using solution:\n{solution}"
    )

    # --------------------------------------------------------
    # LightningSim
    # --------------------------------------------------------

    lightningsim = run_lightningsim(
        solution,
        model_name,
    )

    if lightningsim["status"] != "PASSED":

        return {
            "model": model_name,
            "status": "FAILED",
            "vitis_cosimulation": vitis,
            "lightningsim": lightningsim,
            "solution": str(solution),
        }

    # --------------------------------------------------------
    # Speedup
    # --------------------------------------------------------

    vitis_time = vitis["runtime_seconds"]
    lightning_time = (
        lightningsim["runtime_seconds"]
    )

    speedup = (
        vitis_time / lightning_time
        if lightning_time > 0
        else None
    )

    print("\n" + "-" * 70)
    print("TIMING COMPARISON")
    print("-" * 70)

    print(
        f"Vitis co-simulation: "
        f"{vitis_time:.3f} s"
    )

    print(
        f"LightningSim:        "
        f"{lightning_time:.3f} s"
    )

    print(
        f"Speedup:             "
        f"{speedup:.2f}x"
    )

    return {
        "model": model_name,
        "status": "PASSED",
        "solution": str(solution),

        "vitis_cosimulation": vitis,

        "lightningsim": lightningsim,

        "timing_comparison": {
            "speedup": speedup,
        },
    }


# ============================================================
# Main
# ============================================================

def main():

    print("=" * 80)
    print("hls4ml Vitis vs LightningSim Timing Benchmark")
    print("=" * 80)

    results = {
        "benchmark": {
            "num_models": len(MODELS),
            "models": MODELS,
            "lightningsim_environment": LIGHTNINGSIM_ENV,
        },
        "results": [],
    }

    for index, model_name in enumerate(
        MODELS,
        start=1,
    ):

        print(
            f"\n\n"
            f"######## MODEL "
            f"{index}/{len(MODELS)} ########"
        )

        try:

            result = benchmark_model(
                model_name
            )

            results["results"].append(
                result
            )

            # Save after every model.

            save_results(results)

            print(
                f"\n✓ Results saved to "
                f"{RESULTS_FILE}"
            )

        except KeyboardInterrupt:

            print(
                "\nBenchmark interrupted."
            )

            save_results(results)
            break

        except Exception as exc:

            print(
                f"\n✗ Unexpected error for "
                f"{model_name}: {exc}"
            )

            results["results"].append({
                "model": model_name,
                "status": "FAILED",
                "error": str(exc),
            })

            save_results(results)

    print("\n\n" + "=" * 80)
    print("TIMING BENCHMARK COMPLETE")
    print("=" * 80)

    print(
        f"\nResults:"
        f"\n{RESULTS_FILE}"
    )


if __name__ == "__main__":
    main()